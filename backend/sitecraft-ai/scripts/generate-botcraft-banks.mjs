// Generates the ready-made BotCraft question banks in botcraft-banks/.
//
//   BOTCRAFT_GEMINI_API_KEY=... node scripts/generate-botcraft-banks.mjs [type-key ...]
//   node scripts/generate-botcraft-banks.mjs --from <bank.json> <type-key>   (import an earlier run)
//
// With no type keys, generates every type in botcraft-shop-types.js that has
// no bank yet. Always rebuilds botcraft-banks/index.js.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateQuestionBank, toBankRecord } from "../botcraft-question-bank.js";
import { SHOP_TYPES } from "../botcraft-shop-types.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bankDir = join(root, "botcraft-banks");
const args = process.argv.slice(2);

function toBankFile(type, bank) {
  return toBankRecord(type.key, type.name, bank);
}

function writeIndex() {
  const files = readdirSync(bankDir).filter(f => f.endsWith(".json")).sort();
  const names = files.map(f => f.replace(/\.json$/, ""));
  const ident = n => "bank_" + n.replace(/[^a-z0-9]/g, "_");
  writeFileSync(join(bankDir, "index.js"),
    "// Generated by scripts/generate-botcraft-banks.mjs. Do not edit by hand.\n" +
    names.map(n => `import ${ident(n)} from "./${n}.json" with { type: "json" };`).join("\n") +
    "\n\nexport const QUESTION_BANKS = {\n" +
    names.map(n => `  ${JSON.stringify(n)}: ${ident(n)}`).join(",\n") +
    "\n};\n");
  console.log(`index.js: ${names.length} banks`);
}

if (args[0] === "--from") {
  const [, file, key] = args;
  const type = SHOP_TYPES.find(t => t.key === key);
  if (!type) throw new Error(`Unknown type ${key}`);
  const out = toBankFile(type, JSON.parse(readFileSync(file, "utf8")));
  writeFileSync(join(bankDir, `${key}.json`), JSON.stringify(out, null, 1));
  console.log(`${key}: imported ${out.question_count} questions`);
  writeIndex();
} else {
  const env = { BOTCRAFT_GEMINI_API_KEY: process.env.BOTCRAFT_GEMINI_API_KEY };
  if (!env.BOTCRAFT_GEMINI_API_KEY) throw new Error("Set BOTCRAFT_GEMINI_API_KEY.");
  const wanted = args.length ? SHOP_TYPES.filter(t => args.includes(t.key)) : SHOP_TYPES.filter(t => !existsSync(join(bankDir, `${t.key}.json`)));
  for (const type of wanted) {
    const start = Date.now();
    try {
      const bank = await generateQuestionBank(env, { shopType: type.description, city: "India", log: m => console.log(`  [${type.key}] ${m}`) });
      const out = toBankFile(type, bank);
      writeFileSync(join(bankDir, `${type.key}.json`), JSON.stringify(out, null, 1));
      console.log(`${type.key}: ${out.question_count} questions in ${Math.round((Date.now() - start) / 1000)}s`);
      writeIndex();
    } catch (error) {
      console.log(`${type.key}: FAILED ${error.message}`);
    }
  }
  writeIndex();
}
